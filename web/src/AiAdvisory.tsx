import type { ReactNode } from 'react';
import { Sparkles } from 'lucide-react';
import { DateLabel } from './RepositoryUI';

export const aiFooter = "Generated by Workers AI through this installation's private AI Gateway. It can be wrong; nothing is published until you act.";

// One frame for every Workers AI result: what it says, which model, what it read, which source it describes, and whether that source is still current.
export function AiAdvisory({ title, label, model, reads, commitId, at, current, draft = false, actions, children }: {
  title: string; label: string; model?: string; reads: string; commitId?: string; at?: string;
  // true: the source it describes is still current; false: out of date; undefined: not compared.
  current?: boolean; draft?: boolean; actions?: ReactNode; children: ReactNode;
}) {
  return <section className="browser-panel ai-advisory" aria-label={label}>
    <div className="browser-panel-heading"><h3><Sparkles size={15} aria-hidden="true"/>{title}</h3>
      <span className="ai-advisory-flags">{current === undefined ? null : <span className={`visibility ${current ? 'available' : 'configured'}`}><span className="status-dot"/>{current ? 'Current' : 'Out of date'}</span>}<span className="visibility">{draft ? 'Untrusted draft' : 'Advisory'}</span></span>
      {actions}</div>
    <div className="ai-advisory-body">{children}</div>
    <p className="ai-provenance">{model ? <span className="ai-model-chip" title="Workers AI model">{model}</span> : null}<span>{reads}</span>{commitId ? <span>Based on <code title={commitId}>{commitId.slice(0, 12)}</code></span> : null}{at ? <span><DateLabel value={at} relative/></span> : null}</p>
    <p className="ai-advisory-footer">{aiFooter}</p>
  </section>;
}

// One row per option: a label, a meter and its percentage. The chosen option carries the accent; values stay in text ink.
export function ProbabilityBar({ label, options, chosen }: { label: string; options: { key: string; label: string; probability: number }[]; chosen?: string }) {
  return <ul className="probability-bar" aria-label={label}>{options.map(option => {
    const percent = Math.round(Math.min(1, Math.max(0, option.probability)) * 100);
    return <li key={option.key} className={option.key === chosen ? 'chosen' : undefined}>
      <span className="probability-label">{option.label}{option.key === chosen ? <span className="sr-only"> (recommended)</span> : null}</span>
      <meter min={0} max={1} value={option.probability} aria-label={`${option.label}: ${percent}%`}/>
      <span className="probability-value">{percent}%</span>
    </li>;
  })}</ul>;
}
